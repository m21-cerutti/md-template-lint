// Verify that src/generated/ is exactly what `pnpm run gen:parser` produces.
//
// Generates both grammars (scripts/gen-parser.ts) into a fresh temporary
// directory, then compares that output with src/generated/: a changed file, a
// missing file or an extra (stale or hand-added) file fails with exit code 1.
// src/generated/ itself is never modified. Works whether or not src/generated/
// is committed.
import { createHash } from "node:crypto";
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import process from "node:process";
import { generateParser, generatedDir } from "./gen-parser.ts";

/** File name -> sha256 of its content, for every file in a directory. */
function snapshot(directory: string): Map<string, string> {
  const hashes = new Map<string, string>();
  if (!existsSync(directory)) return hashes;
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (entry.isFile()) {
      const content = readFileSync(join(directory, entry.name));
      hashes.set(entry.name, createHash("sha256").update(content).digest("hex"));
    }
  }
  return hashes;
}

const scratchRoot = mkdtempSync(join(tmpdir(), "md-template-lint-parser-"));
let expected: Map<string, string>;
try {
  const scratch = join(scratchRoot, "generated");
  generateParser(scratch);
  expected = snapshot(scratch);
} finally {
  rmSync(scratchRoot, { recursive: true, force: true });
}
const actual = snapshot(generatedDir);

const problems: string[] = [];
for (const [name, hash] of expected) {
  if (!actual.has(name)) problems.push(`missing: ${name}`);
  else if (actual.get(name) !== hash) problems.push(`differs: ${name}`);
}
for (const name of actual.keys()) {
  if (!expected.has(name)) problems.push(`not generated by the grammars: ${name}`);
}

if (problems.length > 0) {
  process.stderr.write(
    "check:parser FAILED: src/generated/ does not match grammar/*.g4.\n" +
      problems.map((problem) => `  - ${problem}\n`).join("") +
      "Run `pnpm run gen:parser` (it empties src/generated/ first) and commit.\n",
  );
  process.exit(1);
}
process.stdout.write(`check:parser OK: ${actual.size} generated files match the grammars.\n`);
